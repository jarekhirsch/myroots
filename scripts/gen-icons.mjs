const src = 'node_modules/@phosphor-icons/core/assets';
const out = 'src/lib/icons';
const inner = (w, n) => {
  const f = path.join(src, w, w === 'regular' ? `${n}.svg` : `${n}-${w}.svg`);
  const s = fs.readFileSync(f, 'utf8');
  return s.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<rect width="256" height="256" fill="none"\s*\/>/g, '').trim();
};

const camel = (n) => n.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
if (process.argv[1] && import.meta.url.endsWith(path.basename(process.argv[1]))) {
  fs.mkdirSync(out, { recursive: true });
  const names = [...new Set(Object.values(MAP))];
  for (const n of names) {
    const body = `<!-- Phosphor Icons "${n}" (MIT). Generated by scripts/gen-icons.mjs, do not edit. -->
<script lang="ts">
  let { size = 24, strokeWidth: _sw = undefined, fill = undefined, color = undefined, class: cls = '', ...rest }: { size?: number | string; strokeWidth?: number | string; fill?: string; color?: string; class?: string; [k: string]: unknown } = $props();
  const w = $derived(fill && fill !== 'none' ? 'f' : Number(size) > 16 ? 'l' : 'r');
</script>

<svg xmlns="http://www.w3.org/2000/svg" width={size} height={size} viewBox="0 0 256 256" fill={color || 'currentColor'} class="ph {cls}" aria-hidden={rest['aria-label'] ? undefined : 'true'} {...rest}>
  {#if w === 'l'}${inner('light', n)}{:else if w === 'f'}${inner('fill', n)}{:else}${inner('regular', n)}{/if}
</svg>
`;
    fs.writeFileSync(path.join(out, `${camel(n)}.svelte`), body);
  }
  console.log('icons', names.length);
}
